/* Website-only shared canvas checks; no AE bridge or renderer loaded. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const demo=path.join(__dirname,'../docs/site/demo');
const edits=require(path.join(demo,'graph_edits.js'));
const layout=require(path.join(demo,'graph_layout.js'));
const view=require(path.join(demo,'graph_view.js'));
const codec=require(path.join(demo,'graph_codec.js'));
let serial=0;const id=()=> (++serial).toString(16).padStart(32,'0');
let graph={version:1,nodes:[],edges:[],optionalRecords:[]};
for(const type of ['emitter','particle','force','output'])graph=edits.apply(graph,{type:'addNode',nodeType:type,position:{x:serial*60,y:serial*70}},id);
const [emitter,particle,force,output]=graph.nodes;
for(const [from,to] of [[emitter,particle],[particle,force],[force,output]])graph=edits.apply(graph,{type:'connect',from:from.id,to:to.id},id);
assert.equal(graph.edges.length,3);
assert(!edits.canConnect(graph,force.id,particle.id),'cycle rejected');
assert(!edits.canConnect(graph,output.id,force.id),'direction rejected');
const before=codec.toHex(graph);
const disconnected=edits.apply(graph,{type:'disconnect',edgeId:graph.edges[0].id,from:emitter.id,to:particle.id},id);
assert.equal(disconnected.edges.length,2);assert.equal(codec.toHex(graph),before,'shared editor preserves input graph');
const connected=edits.apply(disconnected,{type:'connect',from:emitter.id,to:particle.id},id);assert.equal(connected.edges.length,3);
const deleted=edits.apply(graph,{type:'deleteNodes',nodeIds:[force.id]},id);assert.equal(deleted.nodes.length,3);assert(!deleted.edges.some(e=>e.sourceNode===force.id||e.destinationNode===force.id));
const duplicated=edits.apply(graph,{type:'duplicateNodes',nodeIds:[particle.id],offset:{x:28,y:28}},id);assert.equal(duplicated.nodes.length,5);
const moved=edits.apply(graph,{type:'moveNodes',positions:{[particle.id]:{x:400,y:200}}},id);assert.equal(layout.resolve(moved)[particle.id].x,400);
const withTransform=edits.apply(graph,{type:'addNode',nodeType:'transform',position:{x:250,y:150}},id);
const transform=withTransform.nodes[withTransform.nodes.length-1];
const projectedEdge=view.project(withTransform,null,{width:1920,height:1080,pixelAspect:1}).edges.find(e=>e[0]===particle.id&&e[1]===force.id);
const inserted=edits.apply(withTransform,edits.createInsertEdit(transform.id,projectedEdge,{x:300,y:160}),id);
assert.equal(inserted.edges.length,4);assert(!inserted.edges.some(e=>e.sourceNode===particle.id&&e.destinationNode===force.id));
assert(inserted.edges.some(e=>e.sourceNode===particle.id&&e.destinationNode===transform.id));
assert(inserted.edges.some(e=>e.sourceNode===transform.id&&e.destinationNode===force.id));
assert.equal(codec.toHex(withTransform),codec.toHex(codec.fromHex(codec.toHex(withTransform))),'insertion snapshot restores original line');
const allPositions=layout.resolve(inserted);
assert.equal(codec.toHex(edits.apply(inserted,{type:'moveNodes',positions:allPositions},id)),codec.toHex(inserted),'insertion follow-up layout is a no-op for one-step undo');
assert.equal(codec.toHex(codec.fromHex(before)),before,'undo snapshot round trip');
assert.equal(view.project(graph,null,{width:1920,height:1080,pixelAspect:1}).nodes.length,4);
const bundle=fs.readFileSync(path.join(demo,'panel-demo.js'),'utf8');
assert(!/__adobe|evalScript|StarfieldGraphTransactions|postMessage|XMLHttpRequest|fetch\(|localStorage|setInterval|schedulePanelPoll/.test(bundle),'no host or network transport');
for(const name of ['beginNodeDrag','beginPortDrag','nearestConnectionPort','finishMarquee','duplicateSelection','renderEdges','moveNodeDrag','endNodeDrag'])assert(bundle.includes('function '+name+'('),'reused panel UI: '+name);
const html=fs.readFileSync(path.join(demo,'index.html'),'utf8');
assert(html.includes("connect-src 'none'"));assert(!/webview_host|graph_transactions|\.jsx|optional_modules/.test(html));
const home=fs.readFileSync(path.join(__dirname,'../docs/site/index.html'),'utf8');
assert(/<iframe[^>]+sandbox="allow-scripts"/.test(home),'opaque-origin sandbox');
console.log('Shared website canvas checks passed: real edit planner, typed connections/cycles, disconnect/reconnect, delete cleanup, duplicate, move, snapshot restore, view projection and no host/network transport.');
