"use strict";
const assert=require("node:assert/strict"),panelPath=require("./panel_test_paths.cjs");
const view=require(panelPath("js/graph_view.js")),T=view.types;
const node=(id,type,parameters=[])=>({id,type,parameters});
const edge=(id,sourceNode,destinationNode,destinationPort="1")=>({id,sourceNode,destinationNode,sourcePort:"1",destinationPort});
const particle=node("p",T.particle,[{key:"15",type:3,value:4}]);
let graph={nodes:[node("e",T.emitter),particle,node("o",T.output),node("a",T.emitter,[{key:"31",type:3,value:1}])],
    edges:[edge("ep","e","p"),edge("pa","p","a"),edge("ao","a","o")]};
const issue={edge:"ao",source:"a",destination:"o",code:"SF-G101",message:"cannot render Auxiliary directly"};
let result=view.nodeDiagnostics(graph,[issue]);
assert.deepEqual(Object.keys(result).sort(),["a","p"]);
assert.equal(result.a[0].severity,"error");assert.match(result.a[0].message,/Auxiliary cannot connect directly/);
assert.equal(result.p[0].severity,"warning");assert.equal(result.p[0].code,"SF-W101");assert.match(result.p[0].message,/default cube/);
graph.edges.push(edge("eo","e","o"));result=view.nodeDiagnostics(graph,[{...issue,edge:"eo",source:"e"}]);
assert.equal(result.e[0].severity,"error");assert.match(result.e[0].message,/Emitter cannot connect directly/);assert.ok(!result.o);
graph.nodes.push(node("m",T.model),node("s",T.material),node("t",T.material));
graph.edges.push(edge("ms","m","s","2"),edge("st","s","t","2"),edge("tp","t","p","3"));
assert.ok(!view.nodeDiagnostics(graph,[]).p,"geometry through multiple Materials satisfies Model input");
const rejected={edge:"ms",source:"m",destination:"s",code:"SF-G104",message:"rejected geometry"};
result=view.nodeDiagnostics(graph,[rejected]);assert.equal(result.p[0].severity,"warning","projected-out geometry cannot suppress cube warning");assert.equal(result.m[0].severity,"error");
graph.edges.find(e=>e.id==="ms").destinationPort="1";
assert.ok(view.nodeDiagnostics(graph,[]).p,"Material metadata input is not a geometry input");
graph.edges.find(e=>e.id==="ms").sourceNode="t";
assert.ok(view.nodeDiagnostics(graph,[]).p,"Material-only cycle terminates without inventing geometry");
graph.edges.push(edge("mp","m","p","3"));assert.ok(!view.nodeDiagnostics(graph,[]).p,"independent valid geometry wins over a cyclic branch");
graph.edges.find(e=>e.id==="mp").sourcePort="2";assert.ok(view.nodeDiagnostics(graph,[]).p,"wrong output port cannot satisfy geometry");
assert.ok(!view.nodeDiagnostics({...graph,edges:graph.edges.filter(e=>e.id!=="ao")},[issue]).a,"deleted edge masks a cached issue");
assert.ok(!view.nodeDiagnostics(graph,[{...issue,source:"e"}]).a,"reused edge identity with different endpoints masks stale issue");
particle.parameters[0].value=0;assert.ok(!view.nodeDiagnostics(graph,[]).p,"non-model shapes do not request geometry");
assert.deepEqual(view.nodeDiagnostics(null,[issue]),{});
console.log("Node diagnostics: severity/local ownership, fallback cube, Material geometry, cycles, wrong ports and stale edges passed");
